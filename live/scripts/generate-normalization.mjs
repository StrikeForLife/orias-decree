import fs from 'node:fs';
import { pathToFileURL } from 'node:url';
import { documents } from './normalization-schema.mjs';
const q = (v) => "'" + String(v).replaceAll("'", "''") + "'";
const path = (k) => q('$."' + k + '"');
const valueJSON = (value, type) =>
  `CASE ${type} WHEN 'true' THEN 'true' WHEN 'false' THEN 'false' WHEN 'null' THEN 'null' WHEN 'object' THEN ${value} WHEN 'array' THEN ${value} ELSE json_quote(${value}) END`;
const sqlJSON = valueJSON('value', 'type');
const identity = (d) => (d.kind ? `kind=${q(d.kind)}` : '1');
const docExpr = (d) =>
  d.path ? `json_extract(${d.column},${path(d.path)})` : d.column || 'payload';
const docFilter = (d) =>
  `${identity(d)}${d.path ? ` AND json_type(${d.column},${path(d.path)})='object'` : ''}`;
const expectedChildType = (key) =>
  key === 'wounds' ? 'array' : key.startsWith('Level ') ? null : 'object';

export function normalizationSQL() {
  const sql = [
    `-- Generated by node live/scripts/generate-normalization.mjs. Review SQL with the mapping.\n-- Additive: legacy tables and their IDs, values, versions and triggers are retained.\nCREATE TABLE normalization_checks(id TEXT PRIMARY KEY,ok INTEGER NOT NULL CHECK(ok=1));`,
  ];
  // workerd/D1 permits at most 5 compound SELECT terms. OFFSET prevents
  // SQLite from flattening the small child views into a larger compound.
  function compoundView(name, queries, level = 0) {
    if (queries.length > 5) {
      const children = [];
      for (let i = 0; i < queries.length; i += 4) {
        const child = name + '_level_' + level + '_part_' + (children.length + 1);
        compoundView(child, queries.slice(i, i + 4));
        children.push(`SELECT * FROM ${child}`);
      }
      compoundView(name, children, level + 1);
    } else
      sql.push(
        `CREATE VIEW ${name} AS SELECT * FROM (${queries.join(' UNION ALL ')}) LIMIT -1 OFFSET 0;`,
      );
  }
  for (const [table, column] of [
    ['characters', 'sheet'],
    ['characters', 'state'],
    ['definitions', 'payload'],
  ]) {
    sql.push(
      `INSERT INTO normalization_checks SELECT ${q(table + '.' + column)},CASE WHEN NOT EXISTS(SELECT 1 FROM ${table} WHERE CASE WHEN json_valid(${column}) THEN json_type(${column})<>'object' ELSE 1 END) THEN 1 ELSE 0 END;`,
    );
    sql.push(
      `INSERT INTO normalization_checks SELECT ${q(table + '.' + column + '.keys')},CASE WHEN NOT EXISTS(SELECT 1 FROM ${table},json_each(${column}) GROUP BY ${table}.rowid,key HAVING COUNT(*)>1) THEN 1 ELSE 0 END;`,
    );
  }
  for (const key of ['_baseStats', '_growth'])
    sql.push(
      `INSERT INTO normalization_checks SELECT ${q(key + '.keys')},CASE WHEN NOT EXISTS(SELECT 1 FROM characters,json_each(sheet,${path(key)}) WHERE json_type(sheet,${path(key)})='object' GROUP BY characters.id,key HAVING COUNT(*)>1) THEN 1 ELSE 0 END;`,
    );
  sql.push(
    `CREATE TABLE normalization_legacy_characters AS SELECT * FROM characters;\nCREATE TABLE normalization_legacy_definitions AS SELECT * FROM definitions;`,
  );
  for (const d of documents) {
    const pk = d.kind
      ? `id TEXT PRIMARY KEY,kind TEXT NOT NULL DEFAULT ${q(d.kind)} CHECK(kind=${q(d.kind)}),FOREIGN KEY(kind,id) REFERENCES definitions(kind,id) ON DELETE CASCADE`
      : 'id TEXT PRIMARY KEY REFERENCES characters(id) ON DELETE CASCADE';
    const columns = Object.values(d.fields)
      .map((c) => `${c}`)
      .join(',');
    // The table-level composite FK must follow column declarations.
    const parts = pk.split(',FOREIGN KEY');
    sql.push(
      `CREATE TABLE ${d.table}(${parts[0]},${columns},shape_json TEXT NOT NULL,extras_json TEXT NOT NULL${parts[1] ? ',FOREIGN KEY' + parts[1] : ''});`,
    );
    const scalarKeys = Object.keys(d.fields);
    const children = d.children || {};
    const extrasCondition = [
      `key NOT IN(${[...scalarKeys, ...Object.keys(children)].map(q).join(',')})`,
      `(key IN(${scalarKeys.map(q).join(',')}) AND type IN('object','array'))`,
    ];
    for (const k of Object.keys(children)) {
      const t = expectedChildType(k);
      if (t) extrasCondition.push(`(key=${q(k)} AND type<>${q(t)})`);
    }
    const values = scalarKeys.map((k) => `json_extract(doc,${path(k)})`);
    sql.push(
      `CREATE VIEW project_${d.table} AS SELECT id,${values.map((v, i) => v + ' AS ' + Object.values(d.fields)[i]).join(',')},\n(SELECT json_group_object(key,type) FROM json_each(doc)) AS shape_json,\n(SELECT json_group_object(key,json(${sqlJSON})) FROM json_each(doc) WHERE ${extrasCondition.join(' OR ')}) AS extras_json\nFROM (SELECT id,${docExpr(d)} AS doc FROM ${d.source} WHERE ${docFilter(d)});`,
    );
    sql.push(
      `INSERT INTO ${d.table}(id,${columns},shape_json,extras_json) SELECT * FROM project_${d.table};`,
    );
  }
  sql.push(
    `CREATE TABLE character_wounds(character_id TEXT NOT NULL REFERENCES characters(id) ON DELETE CASCADE,ordinal INTEGER NOT NULL,amount,value_type TEXT NOT NULL,PRIMARY KEY(character_id,ordinal));\nINSERT INTO character_wounds SELECT c.id,CAST(j.key AS INTEGER),j.value,j.type FROM characters c,json_each(c.state,'$.wounds') j WHERE json_type(c.state,'$.wounds')='array';\nCREATE TABLE class_perks(class_id TEXT NOT NULL REFERENCES catalog_classes(id) ON DELETE CASCADE,level INTEGER NOT NULL CHECK(level BETWEEN 1 AND 8),description,value_type TEXT NOT NULL,PRIMARY KEY(class_id,level));\nINSERT INTO class_perks SELECT d.id,CAST(substr(j.key,7,1) AS INTEGER),j.value,j.type FROM definitions d,json_each(d.payload) j WHERE d.kind='class' AND j.key IN(${Array.from({ length: 8 }, (_, i) => q(`Level ${i + 1} Perk`)).join(',')});`,
  );
  // Documents are rebuilt from explicit columns, presence/type metadata and extras.
  for (const d of documents) {
    const specialJSON = [];
    for (const [key, table] of Object.entries(d.children || {})) {
      const t = expectedChildType(key);
      let expr;
      if (table === 'character_wounds')
        expr = `(SELECT json_group_array(json(v)) FROM (SELECT ${valueJSON('amount', 'value_type')} AS v FROM character_wounds WHERE character_id=n.id ORDER BY ordinal))`;
      else if (table === 'class_perks')
        expr = `(SELECT ${valueJSON('description', 'value_type')} FROM class_perks WHERE class_id=n.id AND level=${Number(key[6])})`;
      else expr = `(SELECT document FROM read_${table} WHERE id=n.id)`;
      specialJSON.push(
        `WHEN ${q(key)} THEN ${t ? `CASE WHEN f.value=${q(t)} THEN ${expr} ELSE ${valueJSON(`json_extract(n.extras_json,${path(key)})`, 'f.value')} END` : expr}`,
      );
    }
    // json_each(extras_json) uses key equality to support arbitrary unknown JSON keys.
    const scalarCases = Object.entries(d.fields).map(
      ([k, c]) =>
        `WHEN ${q(k)} THEN ${valueJSON(`CASE WHEN f.value IN('object','array') THEN (SELECT value FROM json_each(n.extras_json) WHERE key=f.key) ELSE n.${c} END`, 'f.value')}`,
    );
    const encoded = `CASE f.key ${scalarCases.join(' ')} ${specialJSON.join(' ')} ELSE (SELECT ${sqlJSON} FROM json_each(n.extras_json) WHERE key=f.key) END`;
    sql.push(
      `CREATE VIEW read_${d.table} AS SELECT n.id,(SELECT json_group_object(f.key,json(${encoded})) FROM json_each(n.shape_json) f) AS document FROM ${d.table} n;`,
    );
  }
  sql.push(
    `CREATE VIEW normalized_characters AS SELECT c.id,c.campaign_id,c.owner_email,c.owner_user_id,p.document AS sheet,r.document AS state,c.version,c.edit_class,c.edit_spells FROM characters c JOIN read_character_profiles p ON p.id=c.id JOIN read_character_resources r ON r.id=c.id;`,
  );
  compoundView('normalized_definitions', [
    ...documents
      .filter((d) => d.kind)
      .map(
        (d) =>
          `SELECT d.kind,d.id,n.document AS payload,d.version,d.archived FROM definitions d JOIN read_${d.table} n ON n.id=d.id WHERE d.kind=${q(d.kind)}`,
      ),
    `SELECT * FROM definitions WHERE kind NOT IN(${documents
      .filter((d) => d.kind)
      .map((d) => q(d.kind))
      .join(',')})`,
  ]);
  // Raw relationship rows retain unresolved IDs. Resolved view exposes only real targets.
  sql.push(
    `CREATE VIEW project_character_beliefs AS WITH RECURSIVE parts(character_id,ordinal,rest,belief_id) AS (SELECT id,-1,CAST(COALESCE(beliefs,'') AS TEXT)||',','' FROM character_profiles UNION ALL SELECT character_id,ordinal+1,substr(rest,instr(rest,',')+1),trim(substr(rest,1,instr(rest,',')-1),char(9,10,11,12,13,32,160,5760,8192,8193,8194,8195,8196,8197,8198,8199,8200,8201,8202,8232,8233,8239,8287,12288,65279)) FROM parts WHERE rest<>'') SELECT character_id,ordinal,belief_id FROM parts WHERE belief_id<>'';\nCREATE TABLE character_beliefs(character_id TEXT NOT NULL REFERENCES characters(id) ON DELETE CASCADE,ordinal INTEGER NOT NULL,belief_id TEXT NOT NULL,PRIMARY KEY(character_id,ordinal));\nINSERT INTO character_beliefs SELECT * FROM project_character_beliefs;`,
  );
  compoundView(
    'normalization_references',
    `SELECT 'character' AS source_kind,id AS source_id,'Class' AS field,0 AS ordinal,'class' AS target_kind,class_id AS target_id FROM character_profiles
UNION ALL SELECT 'character',id,'School',0,'school',school_id FROM character_profiles
UNION ALL SELECT 'character',id,'Background',0,'background',background_id FROM character_profiles
UNION ALL SELECT 'character',character_id,'Beliefs',ordinal,'beliefs',belief_id FROM character_beliefs
UNION ALL SELECT 'character',character_id,'Spells',0,'spell',spell_id FROM character_spells
UNION ALL SELECT 'character',character_id,'Weapons',0,'weapon',weapon_id FROM character_weapons
UNION ALL SELECT 'school',id,'Class',0,'class',class_id FROM catalog_schools
UNION ALL SELECT 'school',id,'Belief',0,'beliefs',belief_id FROM catalog_schools
UNION ALL SELECT 'school',id,'Main Spell',0,'spell',main_spell_id FROM catalog_schools
UNION ALL SELECT 'spell',id,'School',0,'school',school_id FROM catalog_spells`.split(
      '\nUNION ALL ',
    ),
  );
  // Composite FK on the resolved edges; dangling original references are never erased.
  sql.push(
    `CREATE TABLE definition_links(source_kind TEXT NOT NULL,source_id TEXT NOT NULL,field TEXT NOT NULL,ordinal INTEGER NOT NULL,target_kind TEXT NOT NULL,target_id TEXT NOT NULL,PRIMARY KEY(source_kind,source_id,field,ordinal,target_kind,target_id),FOREIGN KEY(target_kind,target_id) REFERENCES definitions(kind,id));\nINSERT INTO definition_links SELECT r.* FROM normalization_references r JOIN definitions d ON d.kind=r.target_kind AND d.id=r.target_id WHERE r.source_id IS NOT NULL AND r.target_id IS NOT NULL AND r.target_id<>'';`,
  );
  const refresh = (condition) =>
    `DELETE FROM definition_links WHERE ${condition}; INSERT INTO definition_links SELECT r.* FROM normalization_references r JOIN definitions d ON d.kind=r.target_kind AND d.id=r.target_id WHERE (${condition}) AND r.source_id IS NOT NULL AND r.target_id IS NOT NULL AND r.target_id<>'';`;
  for (const source of ['characters', 'definitions']) {
    for (const event of ['INSERT', 'UPDATE']) {
      const docs = documents.filter((d) => d.source === source);
      const guard = source === 'characters' ? ['sheet', 'state'] : ['payload'];
      const statements = guard.flatMap((c) => [
        `SELECT CASE WHEN json_valid(NEW.${c}) AND json_type(NEW.${c})='object' THEN 1 ELSE RAISE(ABORT,'normalization: invalid JSON object') END;`,
        `SELECT CASE WHEN NOT EXISTS(SELECT 1 FROM json_each(NEW.${c}) GROUP BY key HAVING COUNT(*)>1) THEN 1 ELSE RAISE(ABORT,'normalization: duplicate JSON key') END;`,
      ]);
      if (source === 'characters')
        for (const k of ['_baseStats', '_growth'])
          statements.push(
            `SELECT CASE WHEN NOT EXISTS(SELECT 1 FROM json_each(NEW.sheet,${path(k)}) WHERE json_type(NEW.sheet,${path(k)})='object' GROUP BY key HAVING COUNT(*)>1) THEN 1 ELSE RAISE(ABORT,'normalization: duplicate allocation key') END;`,
          );
      for (const d of docs) {
        // Child rows are removed first by CASCADE; insert parent before perks.
        statements.push(
          `DELETE FROM ${d.table} WHERE id=NEW.id${d.kind ? ` AND NEW.kind=${q(d.kind)}` : ''};`,
        );
        statements.push(
          `INSERT INTO ${d.table}(id,${Object.values(d.fields).join(',')},shape_json,extras_json) SELECT * FROM project_${d.table} WHERE id=NEW.id${d.kind ? ` AND NEW.kind=${q(d.kind)}` : ''};`,
        );
      }
      if (source === 'characters')
        statements.push(
          `DELETE FROM character_wounds WHERE character_id=NEW.id; INSERT INTO character_wounds SELECT NEW.id,CAST(key AS INTEGER),value,type FROM json_each(NEW.state,'$.wounds') WHERE json_type(NEW.state,'$.wounds')='array'; DELETE FROM character_beliefs WHERE character_id=NEW.id; INSERT INTO character_beliefs SELECT * FROM project_character_beliefs WHERE character_id=NEW.id;`,
        );
      else
        statements.push(
          `INSERT INTO class_perks SELECT NEW.id,CAST(substr(key,7,1) AS INTEGER),value,type FROM json_each(NEW.payload) WHERE NEW.kind='class' AND key IN(${Array.from({ length: 8 }, (_, i) => q(`Level ${i + 1} Perk`)).join(',')});`,
        );
      statements.push(
        refresh(
          source === 'characters'
            ? "source_kind='character' AND source_id=NEW.id"
            : '(source_kind=NEW.kind AND source_id=NEW.id) OR (target_kind=NEW.kind AND target_id=NEW.id)',
        ),
      );
      sql.push(
        `CREATE TRIGGER normalize_${source}_${event.toLowerCase()} AFTER ${event === 'UPDATE' ? 'UPDATE OF ' + guard.join(',') : event} ON ${source} BEGIN\n${statements.join('\n')}\nEND;`,
      );
    }
  }
  for (const table of ['character_spells', 'character_weapons'])
    for (const event of ['INSERT', 'UPDATE', 'DELETE'])
      sql.push(
        `CREATE TRIGGER normalize_${table}_${event.toLowerCase()} AFTER ${event} ON ${table} BEGIN ${refresh(`source_kind='character' AND source_id=${event === 'DELETE' ? 'OLD' : 'NEW'}.character_id`)} ${event === 'UPDATE' ? refresh("source_kind='character' AND source_id=OLD.character_id") : ''} END;`,
      );
  // Soft deletion is the application path. These also keep local/CLI deletes coherent.
  for (const table of ['characters', 'definitions']) {
    const condition =
      table === 'characters'
        ? "source_kind='character' AND source_id=OLD.id"
        : '(source_kind=OLD.kind AND source_id=OLD.id) OR (target_kind=OLD.kind AND target_id=OLD.id)';
    sql.push(
      `CREATE TRIGGER normalize_${table}_before_delete BEFORE DELETE ON ${table} BEGIN DELETE FROM definition_links WHERE ${condition}; END;`,
    );
  }
  for (const d of documents)
    for (const c of Object.values(d.fields).filter((c) => c.endsWith('_id')))
      sql.push(`CREATE INDEX ${d.table}_${c} ON ${d.table}(${c});`);
  sql.push(
    `CREATE INDEX character_beliefs_target ON character_beliefs(belief_id); CREATE INDEX definition_links_target ON definition_links(target_kind,target_id);`,
  );
  const issues = [];
  for (const d of documents) {
    const entity = d.kind || 'character',
      scope = d.path || d.column || 'payload';
    issues.push(
      `SELECT ${q(entity)} AS entity,n.id,${q(scope)} AS scope,e.key AS field,CASE WHEN e.key IN(${Object.keys(
        d.fields,
      )
        .concat(Object.keys(d.children || {}))
        .map(q)
        .join(
          ',',
        )}) THEN 'unexpected_shape' ELSE 'unknown_field' END AS reason FROM ${d.table} n,json_each(n.extras_json) e`,
    );
    const required = d.kind
      ? ['system_id', Object.keys(d.fields)[1]]
      : d.table === 'character_profiles'
        ? ['Character Name', 'Level', 'Class', 'School']
        : d.table === 'character_resources'
          ? ['hp', 'temp', 'will', 'wounds']
          : [];
    for (const key of required)
      issues.push(
        `SELECT ${q(entity)},id,${q(scope)},${q(key)},'missing_field' FROM ${d.table} WHERE json_type(shape_json,${path(key)}) IS NULL`,
      );
    if (d.fields.system_id)
      issues.push(
        `SELECT ${q(entity)},id,${q(scope)},'system_id','id_mismatch' FROM ${d.table} WHERE source_id IS NOT NULL AND source_id<>id`,
      );
  }
  issues.push(
    `SELECT source_kind,source_id,'reference',field,'unresolved_reference' FROM normalization_references r WHERE target_id IS NOT NULL AND target_id<>'' AND NOT EXISTS(SELECT 1 FROM definitions d WHERE d.kind=r.target_kind AND d.id=r.target_id)`,
  );
  issues.push(
    `SELECT kind,id,'payload','kind','unknown_kind' FROM definitions WHERE kind NOT IN(${documents
      .filter((d) => d.kind)
      .map((d) => q(d.kind))
      .join(',')})`,
  );
  issues.push(
    `SELECT 'character',p.id,'sheet','Campaign','id_mismatch' FROM character_profiles p JOIN characters c ON c.id=p.id WHERE p.source_campaign IS NOT NULL AND p.source_campaign<>c.campaign_id`,
  );
  issues.push(
    `SELECT 'character',character_id,'state','wounds','unexpected_shape' FROM character_wounds WHERE value_type NOT IN('integer','real')`,
  );
  issues.push(
    `SELECT 'class',class_id,'payload','Level '||level||' Perk','unexpected_shape' FROM class_perks WHERE value_type IN('object','array')`,
  );
  for (const table of ['character_spells', 'character_weapons'])
    issues.push(
      `SELECT 'character',character_id,'reference',${q(table)},'orphan_character_link' FROM ${table} l WHERE NOT EXISTS(SELECT 1 FROM characters c WHERE c.id=l.character_id)`,
    );
  compoundView('normalization_issues', issues);
  sql.push('DELETE FROM normalization_checks;');
  return sql.join('\n\n') + '\n';
}
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href)
  fs.writeFileSync(
    new URL('../migrations/0003_normalize_core.sql', import.meta.url),
    normalizationSQL(),
  );
